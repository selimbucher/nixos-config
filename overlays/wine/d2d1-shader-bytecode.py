"""Writes dlls/d2d1/builtin_shaders.h: the HLSL shaders in dlls/d2d1/device.c,
compiled to bytecode, keyed by a hash of their source.

    python3 d2d1-shader-bytecode.py <vkd3d-compiler> dlls/d2d1/device.c > dlls/d2d1/builtin_shaders.h

d2d1 looks a shader up there by the hash and length of its source and
compiles it at run time when it isn't there, so a shader that fails to
compile here (or a source the parser below misreads) only costs speed.
The profile follows the variable name: *_ps_* is ps_4_0, *_vs_* is vs_4_0,
which is what d2d_factory_get_precompiled_shaders() compiles them with.
"""
import re
import subprocess
import sys
import tempfile

ESCAPES = {"n": 10, "t": 9, "r": 13, "a": 7, "b": 8, "f": 12, "v": 11,
           "\\": 92, "'": 39, '"': 34, "?": 63}


def literals_at(src, pos):
    """The adjacent C string literals starting at pos, comments between them
    skipped, up to the closing ';'; None if anything else comes first."""
    lits = []
    while True:
        m = re.compile(r'\s*(?:"((?:[^"\\\n]|\\.)*)"|/\*.*?\*/|//[^\n]*|(;))', re.S).match(src, pos)
        if not m:
            return None
        if m.group(2):
            return lits
        if m.group(1) is not None:
            lits.append(m.group(1))
        pos = m.end()


def decode(lits):
    """Bytes of adjacent C string literals."""
    out = bytearray()
    for lit in lits:
        i = 0
        while i < len(lit):
            c = lit[i]
            if c != "\\":
                out += c.encode()
                i += 1
                continue
            e = lit[i + 1]
            if e in ESCAPES:
                out.append(ESCAPES[e])
                i += 2
            elif e == "x":
                m = re.match(r"[0-9a-fA-F]+", lit[i + 2:])
                out.append(int(m.group(0), 16) & 0xff)
                i += 2 + len(m.group(0))
            elif e in "01234567":
                m = re.match(r"[0-7]{1,3}", lit[i + 1:])
                out.append(int(m.group(0), 8) & 0xff)
                i += 1 + len(m.group(0))
            else:
                raise ValueError("unknown escape \\" + e)
    return bytes(out)


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


def shader_profile(name):
    """The profile for a *_ps_* or *_vs_* variable, None for anything else."""
    if "_ps_" in name + "_":
        return "ps_4_0"
    if "_vs_" in name + "_":
        return "vs_4_0"
    return None


def main():
    compiler, device_c = sys.argv[1], sys.argv[2]
    src = open(device_c, encoding="utf-8").read()
    entries = []
    for m in re.finditer(r"static const char (\w+_code\w*)\[\] =", src):
        name = m.group(1)
        profile = shader_profile(name)
        lits = literals_at(src, m.end())
        if not profile or lits is None:
            continue
        code = decode(lits)
        with (tempfile.NamedTemporaryFile(suffix=".hlsl") as hlsl,
              tempfile.NamedTemporaryFile(suffix=".dxbc") as dxbc):
            hlsl.write(code)
            hlsl.flush()
            r = subprocess.run([compiler, "-x", "hlsl", "-b", "dxbc-tpf", "-p", profile, "-e", "main",
                                "-o", dxbc.name, hlsl.name], capture_output=True, text=True)
            if r.returncode:
                print(f"d2d1-shader-bytecode: {name} ({profile}) does not compile, "
                      f"left to run time:\n{r.stderr}", file=sys.stderr)
                continue
            entries.append((name, profile, fnv1a64(code), len(code), open(dxbc.name, "rb").read()))

    print("/* Generated by d2d1-shader-bytecode.py from the HLSL in device.c; see")
    print(" * d2d_compile_shader(). */\n")
    for name, profile, h, size, blob in entries:
        print(f"static const BYTE {name}_bytecode[] =\n{{", end="")
        for i, b in enumerate(blob):
            print(("\n    " if i % 16 == 0 else " ") + f"0x{b:02x},", end="")
        print("\n};\n")
    print("static const struct d2d_builtin_shader d2d_builtin_shaders[] =\n{")
    for name, profile, h, size, blob in entries:
        print(f"    {{0x{h:016x}ull, {size}, \"{profile}\", {name}_bytecode, sizeof({name}_bytecode)}},")
    print("    {0}\n};")
    print(f"d2d1-shader-bytecode: {len(entries)} shaders", file=sys.stderr)


main()
